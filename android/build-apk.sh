#!/usr/bin/env bash
# Builds and signs the FieldLedger Android APK from ../index.html — no Gradle / Android Studio needed.
#
# Requirements (Ubuntu/Debian): sudo apt-get install aapt apksigner zipalign dalvik-exchange android-sdk-platform-23 openjdk-17-jdk
# Usage:  android/build-apk.sh            → dist/FieldLedger-<version>.apk + dist/version.json
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$HERE/.." && pwd)"
ANDROID_JAR="${ANDROID_JAR:-/usr/lib/android-sdk/platforms/android-23/android.jar}"
BUILD="$ROOT/build/android"
DIST="$ROOT/dist"

# shellcheck disable=SC1091
source <(grep -E '^[A-Z_]+=' "$HERE/version.properties")
# shellcheck disable=SC1091
source <(grep -E '^[A-Z_]+=' "$HERE/keystore/keystore.properties")
APK_NAME="FieldLedger-${VERSION_NAME}.apk"

echo "==> FieldLedger ${VERSION_NAME} (code ${VERSION_CODE})"
rm -rf "$BUILD"; mkdir -p "$BUILD/gen/com/fieldledger/farm" "$BUILD/classes" "$BUILD/assets/www" "$DIST"

# 1. Web app → assets
cp "$ROOT/index.html" "$BUILD/assets/www/index.html"

# 2. Manifest with version, generated Config.java
sed -e "s/@VERSION_CODE@/${VERSION_CODE}/" -e "s/@VERSION_NAME@/${VERSION_NAME}/" "$HERE/AndroidManifest.xml" > "$BUILD/AndroidManifest.xml"
cat > "$BUILD/gen/com/fieldledger/farm/Config.java" <<JAVA
package com.fieldledger.farm;
/** Generated by build-apk.sh — do not edit. */
final class Config {
    static final String UPDATE_URL = "${UPDATE_URL}";
    private Config() { }
}
JAVA

# 3. Resources + manifest + assets → unsigned APK (also generates R.java)
aapt package -f -m -J "$BUILD/gen" -M "$BUILD/AndroidManifest.xml" -S "$HERE/res" -A "$BUILD/assets" \
  -I "$ANDROID_JAR" -0 arsc -F "$BUILD/app.unsigned.apk"

# 4. Java → class files → classes.dex
javac -nowarn -source 8 -target 8 -encoding UTF-8 -cp "$ANDROID_JAR" -d "$BUILD/classes" \
  $(find "$HERE/src" "$BUILD/gen" -name '*.java') 2>&1 | grep -v -E 'bootstrap classpath|source value 8|target value 8|To suppress warnings|^warning: \[options\]|^[0-9]+ warnings?$|JAVA_TOOL_OPTIONS' || true
dalvik-exchange --dex --min-sdk-version=24 --output="$BUILD/classes.dex" "$BUILD/classes"
(cd "$BUILD" && aapt add -f app.unsigned.apk classes.dex >/dev/null)

# 5. Align + sign (v1 + v2 + v3 signatures)
zipalign -f -p 4 "$BUILD/app.unsigned.apk" "$BUILD/app.aligned.apk"
apksigner sign --ks "$HERE/keystore/$STORE_FILE" --ks-key-alias "$KEY_ALIAS" --ks-pass "pass:$STORE_PASSWORD" --key-pass "pass:$STORE_PASSWORD" \
  --min-sdk-version 24 --out "$DIST/$APK_NAME" "$BUILD/app.aligned.apk"
apksigner verify --min-sdk-version 24 "$DIST/$APK_NAME"
rm -f "$DIST/$APK_NAME.idsig"

# 6. Update manifest for the in-app updater
SHA=$(sha256sum "$DIST/$APK_NAME" | cut -d' ' -f1)
SIZE=$(stat -c %s "$DIST/$APK_NAME")
NOTES="${RELEASE_NOTES:-FieldLedger ${VERSION_NAME}}"
python3 - "$DIST/version.json" <<PY
import json, sys
json.dump({"versionCode": ${VERSION_CODE}, "versionName": "${VERSION_NAME}",
           "apkUrl": "${RELEASE_BASE_URL}/${APK_NAME}", "sha256": "${SHA}", "size": ${SIZE},
           "notes": """${NOTES}"""}, open(sys.argv[1], "w"), indent=2)
PY
echo "==> Built $DIST/$APK_NAME ($SIZE bytes)"
echo "    sha256 $SHA"
echo "==> Publish: upload $APK_NAME and version.json to ${RELEASE_BASE_URL}/"
